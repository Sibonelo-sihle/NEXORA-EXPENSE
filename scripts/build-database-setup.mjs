import { readFileSync, writeFileSync } from "node:fs";
const files = [
  "001_initial_schema.sql",
  "002_secure_saas.sql",
  "003_currency_and_release_security.sql",
  "004_workspace_and_receipt_metadata.sql",
];
const preflight = `-- GENERATED by node scripts/build-database-setup.mjs; use only on the confirmed empty NEXORA project.
-- Atomic setup: failures roll back this entire file. Never paste supabase/tests/bootstrap.sql into Supabase.
begin;
set local search_path=public,extensions,pg_catalog;
do $$begin
 if exists(select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind in ('r','p')) then
 raise exception 'Setup requires an empty public schema. Stop and inspect applied migrations; no data has been changed.';end if;
 if to_regclass('auth.users') is null or to_regclass('storage.objects') is null then
 raise exception 'Run this only in the intended Supabase project with Auth and Storage installed';end if;
end $$;
`;
writeFileSync(
  "supabase/setup.sql",
  preflight +
    files
      .map(
        (file) =>
          `\n-- ${file}\n` +
          readFileSync(`supabase/migrations/${file}`, "utf8")
            .replace(/^begin;\s*$/gm, "")
            .replace(/^commit;\s*$/gm, ""),
      )
      .join("\n") +
    "\ncommit;\n",
);
console.log(
  "Generated supabase/setup.sql from migrations 001–004. No database was contacted.",
);
